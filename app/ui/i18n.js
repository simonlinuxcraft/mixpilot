// Names and labels that read the same in both languages.
const SAME = new Set(['MIXPILOT', 'Mixpilot', 'Autopilot', 'Mixer', 'Sound', 'Game', 'Chat', 'Media', 'Aux', 'Master', 'CHATMIX',
  'Bass Boost', 'Equalizer', 'Ducking', 'Noise Gate', 'Flat', 'Bass', 'Gaming', 'Normal', 'Warm', 'Radio', 'Broadcast', 'EQ', 'Ko-fi']);

function t(s, ...args) {
  let r = s;
  if (LANG !== 'de') {
    if (s in EN) r = EN[s];
    else if (!SAME.has(s)) window.__missing.add(s);
  }
  return r.replace(/\{(\d)\}/g, (_, i) => args[i] ?? '');
}

// Static page texts: every text node and the title, aria-label and placeholder attributes.
function translatePage() {
  document.documentElement.lang = LANG;
  if (LANG === 'de') return;
  const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let n; (n = walk.nextNode());) {
    const s = n.nodeValue.trim();
    if (s) n.nodeValue = n.nodeValue.replace(s, t(s));
  }
  for (const a of ['title', 'aria-label', 'placeholder']) {
    document.querySelectorAll(`[${a}]`).forEach((e) => e.setAttribute(a, t(e.getAttribute(a))));
  }
  document.title = t(document.title);
}
